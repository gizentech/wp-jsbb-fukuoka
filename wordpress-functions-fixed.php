			)
		);
	}
endif;
add_action( 'init', 'twentytwentyfive_register_block_bindings' );

// Registers block binding callback function for the post format name.
if ( ! function_exists( 'twentytwentyfive_format_binding' ) ) :
	/**
	 * Callback function for the post format name block binding source.
	 *
	 * @since Twenty Twenty-Five 1.0
	 *
	 * @return string|void Post format name, or nothing if the format is 'standard'.
	 */
	function twentytwentyfive_format_binding() {
		$post_format_slug = get_post_format();

		if ( $post_format_slug && 'standard' !== $post_format_slug ) {
			return get_post_format_string( $post_format_slug );
		}
	}
endif;

/**
 * カスタム機能: ファイル名をランダムに変更しつつ、タイトルを維持する
 */
function rename_file_only_and_keep_title( $file ) {
    $info = pathinfo( $file['name'] );
    $ext  = empty( $info['extension'] ) ? '' : '.' . $info['extension'];

    // 1. 元のファイル名を一時保存
    $original_title = $info['filename'];

    // 2. 実際のファイル名をランダムなIDに変更
    $file['name'] = uniqid() . $ext;

    // 3. メディア登録時に、タイトルを元の名前に戻す処理
    add_filter( 'wp_insert_attachment_data', function( $data ) use ( $original_title ) {
        $data['post_title'] = $original_title;
        return $data;
    });

    return $file;
}
add_filter( 'wp_handle_upload_prefilter', 'rename_file_only_and_keep_title' );

// メディアライブラリの表示をファイル名ではなくタイトルにする
function icon_display_real_name( $response, $attachment, $meta ) {
    if ( ! empty( $attachment->post_title ) ) {
        $response['title'] = $attachment->post_title;
        $response['filename'] = $attachment->post_title; // 表示上のファイル名をタイトルに偽装
    }
    return $response;
}
add_filter( 'wp_prepare_attachment_for_js', 'icon_display_real_name', 10, 3 );


